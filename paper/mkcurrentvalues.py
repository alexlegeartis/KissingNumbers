#!/usr/bin/env python3
"""Generate the current-registry macros used by the results summary.

The manuscript's ``values.tex`` intentionally preserves the frozen September
snapshot used by the detailed historical checks.  This companion file reads
the authoritative current ``RESULTS.md`` table, so the main results table can
report the October registry without changing the historical derivations.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS = os.path.join(HERE, os.pardir, "RESULTS.md")
OUT = os.path.join(HERE, "current_values.tex")


def number(text):
    return int(re.sub(r"[^0-9]", "", text))


def read_rows():
    rows = {}
    with open(RESULTS, encoding="utf-8") as fh:
        for line in fh:
            cells = [cell.strip() for cell in line.split("|")]
            if (len(cells) < 4 or not cells[1].isdigit()
                    or "*" not in cells[3]):
                continue
            previous = number(cells[2])
            current = number(cells[3].replace("*", ""))
            rows[int(cells[1])] = (previous, current)
    if not rows:
        raise SystemExit("RESULTS.md has no result rows")
    return rows


def tex_number(value):
    return format(value, ",").replace(",", r"\,")


def render(rows):
    lines = [
        r"% GENERATED by paper/mkcurrentvalues.py from ../RESULTS.md.",
        r"% Current registry values for the main results summary.",
        r"\providecommand{\Kcur}[1]{\csname KissCurrent#1\endcsname}",
        r"\providecommand{\Kcurprev}[1]{\csname KissCurrentPrev#1\endcsname}",
        r"\providecommand{\Kcurgain}[1]{\csname KissCurrentGain#1\endcsname}",
        r"\providecommand{\Kcurfac}[1]{\csname KissCurrentFac#1\endcsname}",
        "",
    ]
    for dimension in sorted(rows):
        previous, current = rows[dimension]
        lines.extend([
            r"\expandafter\def\csname KissCurrent%d\endcsname{%s}" %
            (dimension, tex_number(current)),
            r"\expandafter\def\csname KissCurrentPrev%d\endcsname{%s}" %
            (dimension, tex_number(previous)),
            r"\expandafter\def\csname KissCurrentGain%d\endcsname{+%s}" %
            (dimension, tex_number(current - previous)),
            r"\expandafter\def\csname KissCurrentFac%d\endcsname{%.2f}" %
            (dimension, current / float(previous)),
        ])
    return "\n".join(lines) + "\n"


def main():
    text = render(read_rows())
    if "--check" in __import__("sys").argv:
        with open(OUT, encoding="utf-8") as fh:
            current = fh.read()
        if current == text:
            print("current_values.tex is up to date")
            return 0
        print("current_values.tex is stale; run: python paper/mkcurrentvalues.py")
        return 1
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote current_values.tex: %d dimensions" % len(read_rows()))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
